const DAY = 86_400_000;
const weekdays = ['sunday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'];
const months = ['january', 'february', 'march', 'april', 'may', 'june', 'july', 'august', 'september', 'october', 'november', 'december'];
export function isCalendarDate(value: string): boolean {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const time = Date.parse(`${value}T12:00:00Z`);
  return Number.isFinite(time) && new Date(time).toISOString().slice(0, 10) === value;
}
export function schoolLocalDate(instant: Date, timeZone: string): string {
  const parts = new Intl.DateTimeFormat('en-CA', { timeZone, year: 'numeric', month: '2-digit', day: '2-digit' }).formatToParts(instant);
  return ['year', 'month', 'day'].map((type) => parts.find((part) => part.type === type)!.value).join('-');
}
type DateResult = { date: string; policy: string } | { issue: string };
/** Resolve only an exact extracted phrase; never accept a date generated by the model. */
export function resolveDatePhrase(phrase: string, localDate: string): DateResult {
  if (!isCalendarDate(localDate)) return { issue: 'The saved school-local date is invalid.' };
  const value = phrase.trim().toLowerCase().replace(/\s+/g, ' ').replace(/^(?:on|by|for) /, '');
  const base = Date.parse(`${localDate}T12:00:00Z`);
  const add = (days: number) => new Date(base + days * DAY).toISOString().slice(0, 10);
  const offsets: Record<string, number> = { today: 0, tomorrow: 1, yesterday: -1, 'day after tomorrow': 2 };
  if (value in offsets) return { date: add(offsets[value]), policy: 'school-local relative date' };
  if (isCalendarDate(value)) return { date: value, policy: 'explicit ISO date' };
  const named = value.match(/^(\d{1,2})(?:st|nd|rd|th)? (january|february|march|april|may|june|july|august|september|october|november|december) (\d{4})$/);
  if (named) {
    const date = `${named[3]}-${String(months.indexOf(named[2]) + 1).padStart(2, '0')}-${named[1].padStart(2, '0')}`;
    return isCalendarDate(date) ? { date, policy: 'explicit named date' } : { issue: 'The note contains an impossible calendar date.' };
  }
  const weekday = value.match(/^(?:(this|coming|next) )?(sunday|monday|tuesday|wednesday|thursday|friday|saturday)$/);
  if (weekday) {
    if (weekday[1] === 'next') return { issue: '“Next” weekday is ambiguous. Correct the note with an exact date.' };
    const offset = (weekdays.indexOf(weekday[2]) - new Date(base).getUTCDay() + 7) % 7;
    return { date: add(offset), policy: 'nearest named weekday on or after the school-local date' };
  }
  return { issue: 'Use an exact YYYY-MM-DD date, day month year, today, tomorrow, or a named weekday. Ambiguous dates need correction.' };
}
